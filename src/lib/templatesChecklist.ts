/** Retorna o template de checklist correspondente à modalidade do processo. */
export function obterTemplatePorModalidade(modalidade?: string | null): ItemTemplateChecklist[] {
  const mod = (modalidade ?? '').trim().toUpperCase();

  if (mod === 'AMIL') return CHECKLIST_AMIL;
  if (mod === 'ADESÃO ARP' || mod === 'ADESAO ARP') return CHECKLIST_ADESAO_ARP;
  if (mod === 'LICITAÇÃO' || mod === 'LICITACAO') return CHECKLIST_LICITACAO;
  if (mod === 'ARP') return CHECKLIST_ARP;
  if (mod === 'INEX') return CHECKLIST_INEX;

  return CHECKLIST_GENERICO;
}
